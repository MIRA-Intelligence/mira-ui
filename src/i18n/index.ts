export type I18nKey = keyof typeof dict.en

export function t(key: I18nKey, lang: Language, vars?: Record<string, string | number>): string {
  const value = dict[lang]?.[key] ?? dict.en[key] ?? key
  if (!vars) return value
  return value.replace(/\{(\w+)\}/g, (_, token: string) => String(vars[token] ?? `{${token}}`))
}
