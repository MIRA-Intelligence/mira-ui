import { randomBytes } from 'node:crypto'
import { chmod, mkdir, mkdtemp, writeFile } from 'node:fs/promises'
import { existsSync, rmSync } from 'node:fs'
import net from 'node:net'
import { tmpdir } from 'node:os'
import path from 'node:path'

// Interactive SSH prompts for Remote-SSH, the way VS Code Remote-SSH does it:
// ssh calls $SSH_ASKPASS with the prompt as argv[1] whenever it needs input
// (password, key passphrase, one-time code, unknown host key). Our helper runs
// this app's own binary as Node (ELECTRON_RUN_AS_NODE=1), hands the prompt to
// the main process over a private local socket, and prints the user's answer
// for ssh. Answers exist only for that round trip: never stored or logged.

export type SshPromptKind = 'host_key' | 'secret'

export interface SshPromptRequest {
  host: string
  kind: SshPromptKind
  text: string
  // The same prompt was already answered in this attempt (e.g. a wrong password).
  retry: boolean
}

export const PROMPT_TEXT_LIMIT = 4000
export const ANSWER_LIMIT = 4096
const REQUEST_LIMIT = 64 * 1024

// Unknown host keys arrive as one multi-line prompt ending in
// "Are you sure you want to continue connecting (yes/no/[fingerprint])?".
export function classifyPrompt(text: string): SshPromptKind {
  return /continue connecting/i.test(text) ? 'host_key' : 'secret'
}

export interface SshVersion {
  major: number
  minor: number
  windows: boolean
  raw: string
}

export function parseSshVersion(text: string): SshVersion | null {
  const match = text.match(/OpenSSH_(for_Windows_)?(\d+)\.(\d+)/)
  if (!match) return null
  return { major: Number(match[2]), minor: Number(match[3]), windows: Boolean(match[1]), raw: match[0] }
}

const atLeast = (version: SshVersion, major: number, minor: number) =>
  version.major > major || (version.major === major && version.minor >= minor)

// macOS/Linux: ssh runs in its own session without a controlling terminal, so
// every OpenSSH release falls back to SSH_ASKPASS (8.4+ is forced to). Windows
// OpenSSH only honours SSH_ASKPASS in recent releases; Windows 10 ships 8.1,
// which would just fail, so those users keep the key-only behaviour.
export function askpassSupported(platform: NodeJS.Platform, version: SshVersion | null): boolean {
  if (platform !== 'win32') return true
  return version !== null && atLeast(version, 8, 6)
}

export const ASKPASS_MAIN_JS = `'use strict'
// Generated by MIRA: forwards one ssh prompt to the desktop app.
const net = require('net')
const handle = process.env.MIRA_ASKPASS_HANDLE
const nonce = process.env.MIRA_ASKPASS_NONCE
const prompt = process.argv.slice(2).join(' ')
let answered = false
const fail = () => { if (!answered) process.exit(1) }
if (!handle || !nonce) process.exit(1)
const socket = net.connect(handle)
let buffer = ''
socket.setEncoding('utf8')
socket.on('connect', () => socket.write(JSON.stringify({ nonce, prompt }) + '\\n'))
socket.on('data', (chunk) => {
  buffer += chunk
  const end = buffer.indexOf('\\n')
  if (end < 0) { if (buffer.length > 65536) fail(); return }
  let reply = null
  try { reply = JSON.parse(buffer.slice(0, end)) } catch (error) { fail(); return }
  if (!reply || typeof reply.answer !== 'string') { fail(); return }
  answered = true
  process.stdout.write(reply.answer + '\\n', () => process.exit(0))
})
socket.on('error', fail)
socket.on('close', fail)
setTimeout(fail, 600000)
`

export const ASKPASS_SH = `#!/bin/sh
ELECTRON_RUN_AS_NODE=1 exec "$MIRA_ASKPASS_NODE" "$MIRA_ASKPASS_MAIN" "$@"
`

export const ASKPASS_CMD = `@echo off\r
set ELECTRON_RUN_AS_NODE=1\r
"%MIRA_ASKPASS_NODE%" "%MIRA_ASKPASS_MAIN%" %*\r
`

export interface AskpassHelpers {
  script: string
  main: string
}

// Written at runtime into a private directory instead of shipping in the
// app bundle: files inside app.asar cannot be executed by ssh.
export async function writeAskpassHelpers(dir: string, platform: NodeJS.Platform = process.platform): Promise<AskpassHelpers> {
  await mkdir(dir, { recursive: true, mode: 0o700 })
  await chmod(dir, 0o700)
  const main = path.join(dir, 'askpass-main.js')
  const script = path.join(dir, platform === 'win32' ? 'askpass.cmd' : 'askpass.sh')
  await writeFile(main, ASKPASS_MAIN_JS, { mode: 0o600 })
  await writeFile(script, platform === 'win32' ? ASKPASS_CMD : ASKPASS_SH, { mode: 0o700 })
  await chmod(script, 0o700)
  return { script, main }
}

// Control sockets have a ~104-byte path limit on macOS, so they live in a
// short private directory under /tmp rather than the long per-user TMPDIR.
export async function createPrivateRuntimeDir(platform: NodeJS.Platform = process.platform): Promise<string> {
  const base = platform !== 'win32' && existsSync('/tmp') ? '/tmp' : tmpdir()
  return mkdtemp(path.join(base, 'mira-ssh-'))
}

export type PromptHandler = (prompt: string) => Promise<string | null>

export interface AskpassSession {
  env: Record<string, string>
  dispose: () => void
}

export interface AskpassServiceOptions {
  helperDir: () => string
  nodePath: string
  platform?: NodeJS.Platform
  display?: string
}

// One local server for the app's lifetime; each connection attempt registers
// a random nonce, so a helper can only answer for the attempt that spawned it.
export class AskpassService {
  private server: net.Server | null = null
  private handlePath: string | null = null
  private runtimeDir: string | null = null
  private helpers: AskpassHelpers | null = null
  private starting: Promise<void> | null = null
  private readonly handlers = new Map<string, PromptHandler>()
  private readonly platform: NodeJS.Platform

  constructor(private readonly options: AskpassServiceOptions) {
    this.platform = options.platform ?? process.platform
  }

  // Private directory for ssh ControlMaster sockets (macOS/Linux).
  async controlDir(): Promise<string> {
    await this.start()
    return this.runtimeDir!
  }

  async open(handler: PromptHandler): Promise<AskpassSession> {
    await this.start()
    const nonce = randomBytes(24).toString('hex')
    this.handlers.set(nonce, handler)
    const env: Record<string, string> = {
      SSH_ASKPASS: this.helpers!.script,
      SSH_ASKPASS_REQUIRE: 'force',
      MIRA_ASKPASS_NODE: this.options.nodePath,
      MIRA_ASKPASS_MAIN: this.helpers!.main,
      MIRA_ASKPASS_HANDLE: this.handlePath!,
      MIRA_ASKPASS_NONCE: nonce,
    }
    // OpenSSH before 8.4 only uses SSH_ASKPASS when DISPLAY is set.
    if (this.platform !== 'win32') env.DISPLAY = this.options.display || ':0'
    return { env, dispose: () => { this.handlers.delete(nonce) } }
  }

  async close(): Promise<void> {
    this.handlers.clear()
    const server = this.server
    const runtimeDir = this.runtimeDir
    this.server = null
    this.runtimeDir = null
    this.handlePath = null
    this.starting = null
    // Synchronous: this runs while the app quits.
    if (runtimeDir) {
      try { rmSync(runtimeDir, { recursive: true, force: true }) } catch { /* best effort */ }
    }
    if (server) await new Promise<void>((resolve) => server.close(() => resolve()))
  }

  private start(): Promise<void> {
    this.starting ??= this.listen().catch((error) => {
      this.starting = null
      throw error
    })
    return this.starting
  }

  private async listen(): Promise<void> {
    this.helpers = await writeAskpassHelpers(this.options.helperDir(), this.platform)
    this.runtimeDir = await createPrivateRuntimeDir(this.platform)
    this.handlePath = this.platform === 'win32'
      ? `\\\\.\\pipe\\mira-askpass-${randomBytes(12).toString('hex')}`
      : path.join(this.runtimeDir, 'askpass.sock')
    const server = net.createServer((socket) => this.serve(socket))
    await new Promise<void>((resolve, reject) => {
      server.once('error', reject)
      server.listen(this.handlePath!, () => {
        server.off('error', reject)
        resolve()
      })
    })
    this.server = server
  }

  private serve(socket: net.Socket): void {
    let buffer = ''
    let handled = false
    const reply = (answer: string | null) => {
      if (socket.destroyed) return
      socket.end(`${JSON.stringify(answer === null ? { cancel: true } : { answer })}\n`)
    }
    socket.setEncoding('utf8')
    socket.setTimeout(10_000, () => { if (!handled) socket.destroy() })
    socket.on('error', () => socket.destroy())
    socket.on('data', (chunk: string) => {
      if (handled) return
      buffer += chunk
      const end = buffer.indexOf('\n')
      if (end < 0) {
        if (buffer.length > REQUEST_LIMIT) socket.destroy()
        return
      }
      handled = true
      socket.setTimeout(0)
      let request: unknown
      try { request = JSON.parse(buffer.slice(0, end)) } catch { request = null }
      buffer = ''
      const nonce = isRecord(request) && typeof request.nonce === 'string' ? request.nonce : ''
      const prompt = isRecord(request) && typeof request.prompt === 'string' ? request.prompt : ''
      const handler = this.handlers.get(nonce)
      if (!handler) { reply(null); return }
      handler(prompt.slice(0, PROMPT_TEXT_LIMIT))
        .then((answer) => reply(typeof answer === 'string' && answer.length <= ANSWER_LIMIT ? answer : null))
        .catch(() => reply(null))
    })
  }
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value)
}
